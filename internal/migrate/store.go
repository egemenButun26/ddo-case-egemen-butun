package migrate

import (
	"context"
	"database/sql"
	"fmt"
	"time"

	"github.com/pressly/goose/v3/database"
)

// gooseTable, goose sema surum tablosunun adidir. Tum uygulama tablolari gibi
// "ya-" onekiyle baslar. goose'un varsayilan store'u tablo adini tirnaklamadigi
// icin burada tireli adi guvenli bicimde kullanan kucuk bir store var.
const gooseTable = "ya-goose_db_version"

const quotedGooseTable = `"` + gooseTable + `"`

type Store struct{}

var (
	_ database.Store = Store{}
	_ interface {
		TableExists(context.Context, database.DBTxConn) (bool, error)
	} = Store{}
)

func (Store) Tablename() string { return gooseTable }

func (Store) CreateVersionTable(ctx context.Context, db database.DBTxConn) error {
	_, err := db.ExecContext(ctx, `CREATE TABLE `+quotedGooseTable+` (
		id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		version_id bigint NOT NULL,
		is_applied boolean NOT NULL,
		tstamp timestamp NOT NULL DEFAULT now()
	)`)
	if err != nil {
		return fmt.Errorf("surum tablosu olusturulamadi: %w", err)
	}
	return nil
}

func (Store) Insert(ctx context.Context, db database.DBTxConn, req database.InsertRequest) error {
	_, err := db.ExecContext(ctx,
		`INSERT INTO `+quotedGooseTable+` (version_id, is_applied) VALUES ($1, true)`, req.Version)
	return err
}

func (Store) Delete(ctx context.Context, db database.DBTxConn, version int64) error {
	_, err := db.ExecContext(ctx,
		`DELETE FROM `+quotedGooseTable+` WHERE version_id = $1`, version)
	return err
}

func (Store) GetMigration(ctx context.Context, db database.DBTxConn, version int64) (*database.GetMigrationResult, error) {
	var (
		tstamp    time.Time
		isApplied bool
	)
	err := db.QueryRowContext(ctx,
		`SELECT tstamp, is_applied FROM `+quotedGooseTable+` WHERE version_id = $1 ORDER BY tstamp DESC LIMIT 1`,
		version,
	).Scan(&tstamp, &isApplied)
	if err == sql.ErrNoRows {
		return nil, fmt.Errorf("%w: %d", database.ErrVersionNotFound, version)
	}
	if err != nil {
		return nil, err
	}
	return &database.GetMigrationResult{Timestamp: tstamp, IsApplied: isApplied}, nil
}

func (Store) GetLatestVersion(ctx context.Context, db database.DBTxConn) (int64, error) {
	var version sql.NullInt64
	if err := db.QueryRowContext(ctx,
		`SELECT max(version_id) FROM `+quotedGooseTable).Scan(&version); err != nil {
		return -1, err
	}
	if !version.Valid {
		return -1, fmt.Errorf("latest %w", database.ErrVersionNotFound)
	}
	return version.Int64, nil
}

func (Store) ListMigrations(ctx context.Context, db database.DBTxConn) ([]*database.ListMigrationsResult, error) {
	rows, err := db.QueryContext(ctx,
		`SELECT version_id, is_applied FROM `+quotedGooseTable+` ORDER BY id DESC`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var out []*database.ListMigrationsResult
	for rows.Next() {
		var r database.ListMigrationsResult
		if err := rows.Scan(&r.Version, &r.IsApplied); err != nil {
			return nil, err
		}
		out = append(out, &r)
	}
	return out, rows.Err()
}

func (Store) TableExists(ctx context.Context, db database.DBTxConn) (bool, error) {
	var exists bool
	err := db.QueryRowContext(ctx,
		`SELECT EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = current_schema() AND tablename = $1)`,
		gooseTable,
	).Scan(&exists)
	return exists, err
}
